-- Atomically reserve a start request before any paid provider session is created.
-- A repeated owner + client_request_hash returns the original reservation.
drop function if exists public.reserve_keepgoing_job(
  text, text, text, text, text, text, integer, bigint, integer, timestamptz, timestamptz
);

create or replace function public.reserve_keepgoing_job(
  p_job_id text,
  p_owner_subject_hash text,
  p_client_request_hash text,
  p_engine text,
  p_goal_hash text,
  p_definition_hash text,
  p_max_attempts integer,
  p_token_budget_total bigint,
  p_tool_call_budget_total integer,
  p_wall_deadline_at timestamptz,
  p_start_lease_until timestamptz,
  p_tool_profile text,
  p_tool_policy_hash text,
  p_tool_write_capable boolean
)
returns setof public.keepgoing_jobs
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  insert into public.keepgoing_jobs (
    job_id,
    owner_subject_hash,
    client_request_hash,
    engine,
    tool_profile,
    tool_policy_hash,
    tool_write_capable,
    status,
    max_attempts,
    token_budget_total,
    tool_call_budget_total,
    goal_hash,
    definition_hash,
    wall_deadline_at,
    start_lease_until
  )
  values (
    p_job_id,
    p_owner_subject_hash,
    p_client_request_hash,
    p_engine,
    coalesce(nullif(p_tool_profile, ''), 'web'),
    nullif(p_tool_policy_hash, ''),
    coalesce(p_tool_write_capable, false),
    'queued',
    p_max_attempts,
    p_token_budget_total,
    p_tool_call_budget_total,
    p_goal_hash,
    p_definition_hash,
    p_wall_deadline_at,
    p_start_lease_until
  )
  on conflict (owner_subject_hash, client_request_hash) do nothing;

  if p_client_request_hash is null then
    return query
      select * from public.keepgoing_jobs where job_id = p_job_id;
  else
    return query
      select *
      from public.keepgoing_jobs
      where owner_subject_hash = p_owner_subject_hash
        and client_request_hash = p_client_request_hash;
  end if;
end;
$$;

revoke all on function public.reserve_keepgoing_job(
  text, text, text, text, text, text, integer, bigint, integer, timestamptz, timestamptz,
  text, text, boolean
) from public, anon, authenticated;

grant execute on function public.reserve_keepgoing_job(
  text, text, text, text, text, text, integer, bigint, integer, timestamptz, timestamptz,
  text, text, boolean
) to service_role;


-- Remove old terminal orchestration metadata and old safe webhook event rows.
-- Active/incomplete jobs are never deleted by this function.
create or replace function public.cleanup_keepgoing_durable_state(
  p_job_retention_days integer default 30,
  p_event_retention_days integer default 14
)
returns table (
  deleted_jobs bigint,
  deleted_events bigint
)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_deleted_jobs bigint := 0;
  v_deleted_events bigint := 0;
begin
  if p_job_retention_days < 1 or p_job_retention_days > 3650 then
    raise exception 'p_job_retention_days must be between 1 and 3650';
  end if;
  if p_event_retention_days < 1 or p_event_retention_days > 3650 then
    raise exception 'p_event_retention_days must be between 1 and 3650';
  end if;

  delete from public.keepgoing_job_events
  where created_at < now() - make_interval(days => p_event_retention_days);
  get diagnostics v_deleted_events = row_count;

  delete from public.keepgoing_jobs
  where status in ('completed', 'failed', 'cancelled', 'budget_exhausted')
    and updated_at < now() - make_interval(days => p_job_retention_days);
  get diagnostics v_deleted_jobs = row_count;

  return query select v_deleted_jobs, v_deleted_events;
end;
$$;

