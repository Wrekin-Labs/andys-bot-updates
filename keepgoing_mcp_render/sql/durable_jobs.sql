-- KeepGoing v1.2 durable job state.
-- Prototype schema only: review and apply through the normal Supabase migration workflow.
-- Stores orchestration metadata only; raw prompts, model output and credentials are deliberately excluded.

create table if not exists public.keepgoing_jobs (
  job_id text primary key
    check (job_id ~ '^kgj_[0-9a-f]{32}$'),
  owner_subject_hash text not null
    check (char_length(owner_subject_hash) between 16 and 128),
  client_request_hash text,
  engine text not null default 'agents'
    check (engine in ('agents', 'responses')),
  tool_profile text not null default 'web'
    check (tool_profile ~ '^[a-z][a-z0-9_-]{0,63}
  status text not null
    check (status in (
      'queued',
      'working',
      'continuing',
      'input_required',
      'completed',
      'failed',
      'cancelled',
      'budget_exhausted'
    )),
  version bigint not null default 1
    check (version > 0),
  attempt integer not null default 0
    check (attempt >= 0),
  max_attempts integer not null default 6
    check (max_attempts between 1 and 20),
  tokens_used bigint not null default 0
    check (tokens_used >= 0),
  token_budget_total bigint not null default 120000
    check (token_budget_total >= 1000),
  tool_calls_used integer not null default 0
    check (tool_calls_used >= 0),
  tool_call_budget_total integer not null default 30
    check (tool_call_budget_total >= 0),
  goal_hash text,
  definition_hash text,
  completion_marker text
    check (completion_marker is null or completion_marker in ('COMPLETED', 'NEEDS_USER', 'PARTIAL')),
  continuation_needed boolean not null default false,
  continuation_claim_id uuid,
  continuation_idempotency_key text
    check (continuation_idempotency_key is null or char_length(continuation_idempotency_key) between 1 and 256),
  last_assessed_turn_id text,
  start_lease_until timestamptz,
  continuation_lease_until timestamptz,
  repeated_output_count integer not null default 0
    check (repeated_output_count >= 0),
  last_output_hash text,
  safe_error_code text,
  safe_error_message text,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_progress_at timestamptz not null default now(),
  wall_deadline_at timestamptz not null,
  constraint keepgoing_jobs_request_unique
    unique (owner_subject_hash, client_request_hash)
);

-- Add tool-policy provenance when upgrading an earlier v1.2 beta schema.
alter table public.keepgoing_jobs
  add column if not exists tool_profile text not null default 'web';
alter table public.keepgoing_jobs
  add column if not exists tool_policy_hash text;
alter table public.keepgoing_jobs
  add column if not exists tool_write_capable boolean not null default false;

create index if not exists keepgoing_jobs_status_updated_idx
  on public.keepgoing_jobs (status, updated_at);

create index if not exists keepgoing_jobs_owner_updated_idx
  on public.keepgoing_jobs (owner_subject_hash, updated_at desc);

alter table public.keepgoing_jobs enable row level security;

revoke all on table public.keepgoing_jobs from public, anon, authenticated;
grant select, insert, update, delete on table public.keepgoing_jobs to service_role;

comment on table public.keepgoing_jobs is
  'Durable KeepGoing orchestration metadata. Does not store raw prompts, model output, OAuth tokens, activation tokens or passwords.';


